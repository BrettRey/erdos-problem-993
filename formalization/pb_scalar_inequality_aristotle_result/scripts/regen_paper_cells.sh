#!/usr/bin/env bash
# Regenerates PBScalar/PaperCells/Cells{A,B,C}.lean from the certificate JSON.
set -euo pipefail
cd "$(dirname "$0")/.."
for part in "CellsA 4 5 6 7 8 9" "CellsB 10 11 12 13" "CellsC 14 15"; do
  set -- $part; n=$1; shift
  {
    printf 'import PBScalar.PaperCells.Defs\n\n'
    printf '/-! Generated by `scripts/gen_paper_cells.py` from the certificate data: cells `m = %s`. -/\n\n' "$*"
    printf 'namespace PBScalar.Certificate\n'
    python3 scripts/gen_paper_cells.py "$@"
    echo "end PBScalar.Certificate"
  } > "PBScalar/PaperCells/$n.lean"
done
